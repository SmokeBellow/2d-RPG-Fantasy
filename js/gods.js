// ---------------------------------------------------------------- ранги
// rank: -3 Проклятие, -2 Гнев, -1 Немилость, 0 Безразличие, 1 Внимание, 2 Расположение, 3 Покровительство, 4 Избранник
export const RANK_NAMES = {
  '-3': 'Проклятие', '-2': 'Гнев', '-1': 'Немилость', 0: 'Безразличие', 1: 'Внимание', 2: 'Расположение', 3: 'Покровительство', 4: 'Избранник',
};
const CURSE_AT = -60;

export function rankOf(score) {
  if (score >= 80) return 4;
  if (score >= 50) return 3;
  if (score >= 25) return 2;
  if (score >= 10) return 1;
  if (score > -10) return 0;
  if (score > -35) return -1;
  if (score > CURSE_AT) return -2;
  return -3;
}

export function newGods() {
  const g = {};
  for (const id of GOD_IDS) g[id] = 0;
  return g;
}

export const godRank = (s, id) => rankOf(s.gods[id] || 0);

// Меняет мнение бога. Противоположный бог реагирует зеркально, но слабее (на треть).
// Возвращает список смен ранга для знамений: [{ god, from, to }]
export function favor(s, id, delta) {
  const changes = [];
  const apply = (gid, d) => {
    const before = rankOf(s.gods[gid] || 0);
    s.gods[gid] = Math.max(-100, Math.min(100, (s.gods[gid] || 0) + d));
    const after = rankOf(s.gods[gid]);
    if (s.gods[gid] <= CURSE_AT && !s.curses.includes(gid)) s.curses.push(gid);   // проклятие навсегда
    if (after !== before) changes.push({ god: gid, from: before, to: after });
  };
  apply(id, delta);
  const opp = GODS[id].opposed;
  if (opp && Math.abs(delta) >= 3) apply(opp, -Math.round(delta / 3));
  return changes;
}

// ---------------------------------------------------------------- эффекты
export function godEffects(s) {
  const out = {};
  const add = (o) => { for (const [k, v] of Object.entries(o)) out[k] = (out[k] || 0) + v; };
  for (const id of GOD_IDS) {
    const r = rankOf(s.gods[id] || 0);
    if (r >= 2) add(GODS[id].bless[Math.min(2, r - 2)]);
    if (s.curses.includes(id)) add(GODS[id].curse);
  }
  return out;
}

export const isChosen = (s, id) => godRank(s, id) >= 4;

// Слушающая в Храме Семи: описывает ранги образами. Чисел не называет никогда.
export function templeReading(s) {
  return GOD_IDS.map((id) => {
    const r = godRank(s, id);
    let line = GODS[id].ranks[r + 3];
    if (s.curses.includes(id) && r > -3) line += ' Но старое проклятие всё ещё на тебе.';
    return { id, name: GODS[id].name, rank: r, rankName: RANK_NAMES[r], line };
  });
}
