export function epilogue(s) {
  const lines = [];
  for (const [k, vals] of Object.entries(CH)) { const v = s.choices[k]; if (v && vals[v]) lines.push(vals[v]); }
  const chosen = GOD_IDS.filter((g) => godRank(s, g) >= 3).map((g) => GODS[g].name);
  if (chosen.length) lines.push(`За тобой следили и одобряли: ${chosen.join(', ')}.`);
  if (s.curses && s.curses.length) lines.push(`Помнят и тех, кто проклял: ${s.curses.map((g) => GODS[g].name).join(', ')}. Это навсегда.`);
  return lines;
}
