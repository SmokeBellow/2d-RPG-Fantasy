export function epilogue(s) {
  const lines = [];
  for (const [k, vals] of Object.entries(CH)) { const v = s.choices[k]; if (v && vals[v]) lines.push(vals[v]); }
  const end = s.flags && s.flags.ending;
  const hi = (g) => godRank(s, g) >= 3;
  if (end === 'free') {
    const war = hi('kharn') || hi('issa'), law = hi('lyara') || hi('torn');
    lines.push(war && !law ? 'В новой войне ты стоишь рядом с ним. У Кхарна и Иссы на это свои причины, и ни одна из них не про милосердие.'
      : law && !war ? 'Лиара и Торн смотрят на тебя как на перебежчика. Они не простили, но и не отвернулись: так смотрят на тех, кого ещё надеются вернуть.'
      : 'Никто не знает, на чьей ты стороне. Ты и сам не знаешь.');
  }
  if (end === 'close' && s.choices.faction === 'council') lines.push('Совет отчитался перед собой, что угроза устранена. Никто не спросил, что это была за угроза.');
  if (end === 'seal' && s.choices.faction === 'collegium') lines.push('Коллегия установила наблюдение за маяками. Исольда уверяет, что смена вахт не прервётся.');
  if (end === 'throne') lines.push('Те, чьи Лики ты носил, первыми склонили головы. Остальные ещё думают, как к тебе обращаться.');
  const chosen = GOD_IDS.filter((g) => godRank(s, g) >= 3).map((g) => GODS[g].name);
  if (chosen.length) lines.push(`За тобой следили и одобряли: ${chosen.join(', ')}.`);
  if (s.curses && s.curses.length) lines.push(`Помнят и тех, кто проклял: ${s.curses.map((g) => GODS[g].name).join(', ')}. Это навсегда.`);
  return lines;
}
